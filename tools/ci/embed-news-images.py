"""Renders the HOME applet news images from dist/branding and writes the C arrays.

The Switch 2 HOME Menu news viewer only shows an item when the payload carries a
JPEG binary (list_image / main_image in the BCAT msgpack). Veshiru ships them
embedded so the news area always loads, even offline: they are the fallback for
every news entry and the only image the forked feed uses (Veshiru hosts no
release artwork).

Outputs:
  dist/news/veshiru_news_large.jpg   800x450 (main_image, main_image_height=450)
  dist/news/veshiru_news_small.jpg   320x180 (list_image thumbnail)
  src/core/hle/service/bcat/news/news_images.h   embedded byte arrays

Requires: pillow. Usage: python3 tools/ci/embed-news-images.py
"""

from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent.parent
ICON = ROOT / "dist" / "branding" / "veshiru_icon.png"
OUT_DIR = ROOT / "dist" / "news"
HEADER = ROOT / "src" / "core" / "hle" / "service" / "bcat" / "news" / "news_images.h"

TOP = (20, 48, 79)     # #14304F elevated (Deep Current 2.6)
BOTTOM = (10, 21, 38)  # #0A1526 app background (Deep Current 2.6)

SIZES = {"large": (800, 450), "small": (320, 180)}


def render(name: str) -> bytes:
    width, height = SIZES[name]
    canvas = Image.new("RGB", (width, height))
    draw = ImageDraw.Draw(canvas)
    for y in range(height):
        t = y / (height - 1)
        draw.line([(0, y), (width, y)], fill=tuple(int(top + (bottom - top) * t) for top, bottom in zip(TOP, BOTTOM)))
    icon = Image.open(ICON).convert("RGBA")
    side = int(height * 0.72)
    side -= side % 2
    icon = icon.resize((side, side), Image.LANCZOS)
    canvas.paste(icon, ((width - side) // 2, (height - side) // 2), icon)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    path = OUT_DIR / f"veshiru_news_{name}.jpg"
    canvas.save(path, "JPEG", quality=88, optimize=True, progressive=False)
    return path.read_bytes()


def emit_array(out: list[str], name: str, data: bytes) -> None:
    out.append(f"inline constexpr u8 kVeshiruNews{name}[] = {{")
    for offset in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[offset:offset + 16]) + ",")
    out.append("};")
    out.append(f"inline constexpr size_t kVeshiruNews{name}Size = {len(data)};")
    out.append("")


def main() -> None:
    blobs = {name: render(name) for name in SIZES}
    lines = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "",
        "// Generated by tools/ci/embed-news-images.py from dist/branding/veshiru_icon.png.",
        "// Do not edit by hand: edit the script and re-run it to change the artwork.",
        "",
        "#pragma once",
        "",
        "#include <cstddef>",
        "",
        "#include \"common/common_types.h\"",
        "",
        "namespace Service::News {",
        "",
    ]
    for name, data in blobs.items():
        emit_array(lines, name.capitalize(), data)
    lines.append("} // namespace Service::News")
    lines.append("")
    HEADER.write_text("\n".join(lines))
    for name, data in blobs.items():
        print(f"veshiru_news_{name}.jpg: {len(data)} bytes")
    print(f"wrote {HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
